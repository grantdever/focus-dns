"""systemd glue: the generated flip timer and the one-shot restore after a pass or Block now.

Denylist entries ignore NextDNS Recreation Time, and NextDNS holds only one coarse window per day, so
focus-flip.timer runs `focus reconcile` at every edge of every list's windows (plus each midnight).
The same runs apply queued changes when a list unlocks. Its OnCalendar lines live in a drop-in that
is regenerated from all lists' hours whenever they change. focus-reconcile.timer (every 5 min)
backstops it.
"""
from __future__ import annotations

import math
import os
import subprocess
import sys
import time

from .config import REPO
from .schedule import ABBR, DAYS, edge_times, validate_hours, validate_timezone


def render_dropin(settings: dict) -> str:
    tz = validate_timezone(settings["timezone"])
    weeks = [validate_hours(L["hours"]) for L in settings["lists"]]
    by_time: dict[str, list[str]] = {}
    for d in DAYS:
        edges = sorted({t for hours in weeks for t in edge_times(hours[d])})
        for t in edges:
            by_time.setdefault(t, []).append(ABBR[d])
    lines = ["# Generated by focus from the hours table; rewritten whenever the hours change.",
             "[Timer]", "OnCalendar=", f"OnCalendar=*-*-* 00:00:00 {tz}"]
    for t in sorted(by_time):
        lines.append(f"OnCalendar={','.join(by_time[t])} *-*-* {t}:00 {tz}")
    return "\n".join(lines) + "\n"


def _run(cmd: list[str]) -> tuple[int, str]:
    try:
        p = subprocess.run(cmd, capture_output=True, text=True, timeout=30)
        return p.returncode, (p.stderr or p.stdout).strip()
    except (OSError, subprocess.TimeoutExpired) as e:
        return 1, str(e)


def sync_dropin(cfg, settings: dict, runner=_run) -> bool:
    """Write the drop-in if it differs and reload systemd. Returns True if it changed."""
    text = render_dropin(settings)
    path = cfg.flip_dropin
    try:
        if path.read_text() == text:
            return False
    except OSError:
        pass
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(".schedule.conf.tmp")
    tmp.write_text(text)
    os.replace(tmp, path)
    if cfg.systemd:
        runner(["systemctl", "--user", "daemon-reload"])
        runner(["systemctl", "--user", "try-restart", "focus-flip.timer"])
    return True


def schedule_reconcile_at(cfg, at: float, runner=_run, now: float | None = None) -> tuple[int, str]:
    """One-shot `focus reconcile` at `at` (end of a pass or Block now), same sandbox as the units."""
    if not cfg.systemd:
        return 0, "systemd disabled"
    secs = max(1, math.ceil(at - (time.time() if now is None else now)))
    rw = f"{cfg.state_dir} -{cfg.flip_dropin_dir}"
    cmd = ["systemd-run", "--user", "--quiet", "--collect", f"--unit=focus-restore-{int(at)}",
           f"--on-active={secs}s", "--timer-property=AccuracySec=1s",
           "-p", f"WorkingDirectory={REPO}", "-p", "NoNewPrivileges=yes", "-p", "ProtectSystem=strict",
           "-p", "ProtectHome=read-only", "-p", f"ReadWritePaths={rw}",
           sys.executable, "-m", "focus", "reconcile"]
    return runner(cmd)
